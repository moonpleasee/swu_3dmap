"""Add conservative, individually parameterized inferred exteriors to every unreferenced building."""
import json, pathlib, copy, math, re

ROOT=pathlib.Path(__file__).resolve().parents[1]
DATA=ROOT/'public/data/campus.json'
PROFILES=ROOT/'data-sources/exterior-profiles.json'
OUT=ROOT/'work'/'inferred-exteriors'
OUT.mkdir(parents=True,exist_ok=True)
data=json.loads(DATA.read_text(encoding='utf8'))
profiles=json.loads((OUT/'before-profiles.json').read_text(encoding='utf8')) if (OUT/'before-profiles.json').exists() else json.loads(PROFILES.read_text(encoding='utf8'))
# Preserve both explicit single-photo profiles and garden-photo dorm profiles generated by enrich-data.
ref_ids={str(f['id']) for f in data['buildings'] if f.get('exterior',{}).get('basis') in ('single-photo','garden-photo')}
refs={k:copy.deepcopy(v) for k,v in profiles.items() if k in ref_ids}
for f in data['buildings']:
    if str(f['id']) in ref_ids and str(f['id']) not in profiles:
        # garden-photo profiles are generated from dormGroup; their source file entry is intentionally absent.
        continue
for k,v in profiles.items():
    if v.get('basis') in ('single-photo','garden-photo') and k not in refs: raise RuntimeError(k)
if not (OUT/'before-profiles.json').exists():
    (OUT/'before-profiles.json').write_text(json.dumps(profiles,ensure_ascii=False,indent=2),encoding='utf8')
if not (OUT/'before-campus.json').exists():
    (OUT/'before-campus.json').write_text(json.dumps(data,ensure_ascii=False,indent=2),encoding='utf8')

palettes={
 'residential':('#d8c6ad','#eee5d5','#8a948b','#566e73','#8b8879'),
 'dormitory':('#d4b18f','#eee1ca','#b57d61','#536c72','#777e72'),
 'academic':('#d9d8ca','#e8e8dc','#b8b4a0','#536d74','#8a9186'),
 'lab':('#ccd8d1','#eef0e7','#8fa99e','#4e6b70','#7f8b86'),
 'canteen':('#dfd0b8','#ede5d4','#c09770','#4d7074','#8c887a'),
 'commercial':('#d6c3aa','#f0e8d7','#477d72','#466b70','#65766e'),
 'greenhouse':('#aac4b9','#d8ebe1','#779b92','#5d8d8a','#77968c'),
 'service':('#c6c9bf','#e1e2d8','#8b9188','#536b6c','#747b73'),
 'sports':('#c8d1ca','#e7ece3','#6c8e84','#527a7c','#74877d'),
 'hospital':('#d4d9d0','#eff0e9','#6e9085','#4e6d70','#808b83'),
 'unknown':('#d5d3c6','#e5e4d8','#a7aa9c','#526a70','#858b81'),
}

# The model's local coordinates are derived from the same OSM snapshot that
# supplies the building polygons.  Keep road segments in that coordinate
# system, so an inferred entrance is tied to this building's actual footprint
# and nearby access line instead of its display name.
road_segments=[]
for road in data.get('roads',[]):
    pts=road.get('points',[])
    road_segments.extend(zip(pts,pts[1:]))

def point_segment_distance(p,a,b):
    dx,dy=b[0]-a[0],b[1]-a[1]
    den=dx*dx+dy*dy
    t=max(0,min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/den)) if den else 0
    q=(a[0]+t*dx,a[1]+t*dy)
    return math.hypot(p[0]-q[0],p[1]-q[1])

def cls(f):
    t=f.get('tags',{}); typ=t.get('building','')
    name=(f.get('displayName','')+' '+f.get('originalName','')).lower()
    if typ=='greenhouse' or '温室' in name:return 'greenhouse'
    if typ in ('dormitory','residential','apartments') or '舍' in name or '公寓' in name:return 'dormitory' if typ=='dormitory' or '舍' in name else 'residential'
    if typ in ('hospital','clinic') or '医院' in name:return 'hospital'
    if typ in ('commercial','retail','supermarket') or any(x in name for x in ('超市','商业','商店','小吃','市场')):return 'commercial'
    if typ in ('cafe','restaurant','food_court') or any(x in name for x in ('食堂','餐厅','餐饮')):return 'canteen'
    if typ in ('sports_centre','sports_hall','stadium') or any(x in name for x in ('体育','游泳','网球','羽毛球')):return 'sports'
    if any(x in name for x in ('实验室','实验楼','研究','检测','基因','磁共振')):return 'lab'
    if typ in ('service','warehouse','storage','industrial','farm','animal_shelter') or any(x in name for x in ('物业','养殖','机房','泵房','车库','库','服务')):return 'service'
    if typ in ('university','college','school','office','civic') or any(x in name for x in ('学院','教学','图书馆','行政','培训','楼','中心')):return 'academic'
    return 'unknown'

def edge_mid(poly):
    # Prefer the footprint edge nearest an actual mapped road.  If a polygon
    # has no nearby road segment, fall back to its longest edge.  Both choices
    # are tied to this building's OSM polygon, never to a name lookup.
    edges=[]
    for a,b in zip(poly,poly[1:]+poly[:1]):
        d=math.hypot(b[0]-a[0],b[1]-a[1])
        if d>.12:
            mid=((a[0]+b[0])/2,(a[1]+b[1])/2)
            near=min((point_segment_distance(mid,u,v) for u,v in road_segments),default=999)
            edges.append((near,-d,a,b))
    if not edges:return None
    nearest=min(edges)
    # Ignore a road that is far beyond the building footprint and use the
    # longest edge instead; the threshold is in the same local map units.
    if nearest[0]>3.0:nearest=min(edges,key=lambda e:e[1])
    return [round((nearest[2][0]+nearest[3][0])/2,3),round((nearest[2][1]+nearest[3][1])/2,3),round(-nearest[1],3),round(nearest[0],3)]

def profile(f,index):
    c=cls(f); wall,trim,accent,glass,roof=palettes[c]
    edge=edge_mid(f['polygon']); longest=edge[2] if edge else 1; road_distance=edge[3] if edge else None
    levels=f.get('levels') or max(1,round((f.get('height') or .9)/.33))
    small=(f.get('height') or 1)<.65 or longest<1.0
    roof_style='hip' if c=='greenhouse' else ('flat' if c not in ('residential','dormitory') else ('hip' if index%4==0 else 'flat'))
    facade={'dormitory':'balcony','residential':'balcony','academic':'bands','lab':'louver','canteen':'curtain','commercial':'curtain','greenhouse':'curtain','service':'regular','sports':'frame','hospital':'bands','unknown':'regular'}[c]
    bay={'dormitory':.38,'residential':.42,'academic':.52,'lab':.48,'canteen':.62,'commercial':.5,'greenhouse':.46,'service':.72,'sports':.7,'hospital':.55,'unknown':.55}[c]
    p={'basis':'inferred','modelStatus':'configured-unverified','inferenceRevision':'inferred-exteriors-2026-09-26',
       'wall':wall,'trim':trim,'accent':accent,'glass':glass,'frame':trim,'base':'#858b82','roofColor':roof,
       'roofStyle':roof_style,'roofRise':.24 if c=='greenhouse' else .32,'facade':facade,'bay':bay,
       'windowWidth':.62 if not small else .72,'windowHeight':.62 if not small else .66,'frameWidth':.012,
       'entry':'canopy','entryWidth':round(max(.38,min(1.15,longest*.32)),2),'entryFloors':1,
       'entryPoint':edge[:2] if edge else f.get('center',[0,0]),'entrySteps':1 if small else (2 if levels<=2 else 3),
       'porchDepth':.18 if small else .26,'entryBasis':'inferred','entryNote':'入口位置按本栋OSM多边形上最接近校内道路的外墙边估算，门厅、台阶与雨棚尚无本栋照片核实。',
       'mapObjectId':str(f['id']),'mapSourceId':str(f['sourceId']),'mapCenter':[round(v,3) for v in f.get('center',[0,0])],
       'footprintEdgeLength':round(longest,3),'nearestRoadDistance':road_distance,
       'source':'https://www.openstreetmap.org/'+('relation/'+f['sourceId'][1:] if str(f['sourceId']).startswith('r') else 'way/'+str(f['sourceId'])),
       'observations':[f'按本栋OSM对象 {f["id"]} 的多边形、中心点、最近道路和用途“{c}”建立的独立估算外观。',
                      '墙面、窗格、屋顶收边与入口已按同类建筑比例配置，不能视为本栋实拍还原。'],
       'dimensionsNote':'层数沿用当前地图/资料值；立面尺寸、颜色和入口朝向待现场或本栋照片核实。'}
    if c in ('dormitory','residential'):p.update({'balcony':'rooms','ac':True})
    if c=='greenhouse':p.update({'wallFinish':'glass','frame':'#d7eee4','roofRise':.22,'facade':'curtain'})
    if c=='lab':p.update({'wallFinish':'panel','sunhood':True})
    if c=='service':p.update({'louver':True,'entryWidth':round(min(p['entryWidth'],.75),2),'entrySteps':1})
    if c=='sports':p.update({'trim':'#d9e4da','roofColor':'#738880','entryWidth':round(min(p['entryWidth'],1.35),2)})
    if c=='commercial':p.update({'accent':'#3f756a','entry':'glass-canopy'})
    return p

new=[]; skipped=[]
for i,f in enumerate(data['buildings']):
    fid=str(f['id'])
    if fid in ref_ids:
        skipped.append(fid);continue
    profiles[fid]=profile(f,i);new.append(fid)
if any(k in ref_ids and k not in refs for k in profiles): pass
if any(str(f['id']) in ref_ids and str(f['id']) in profiles and profiles[str(f['id'])].get('basis') not in ('single-photo','garden-photo') for f in data['buildings']): raise RuntimeError('reference profile overwritten')
PROFILES.write_text(json.dumps(profiles,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
(OUT/'inferred-ids.json').write_text(json.dumps(new,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
print(json.dumps({'reference_preserved':len(skipped),'inferred_added':len(new),'profile_total':len(profiles)},ensure_ascii=False))
